package com.xunjia.framework.common.constant;

/**
 * 日期时间常量
 */
public class DateTimeConst {

    public static final long SECOND = 1000;

    public static final long MINUTE = SECOND * 60;

    public static final long HOUR = MINUTE * 60;

    public static final long DAY = HOUR * 24;

    public static final long WEEK = DAY * 7;

    public static final long MONTH_31 = DAY * 31;

    public static final long MONTH_30 = DAY * 30;

    public static final long MONTH_29 = DAY * 29;

    public static final long MONTH_28 = DAY * 28;

    public static final long YEAR_365 = DAY * 365;

    public static final long YEAR_366 = DAY * 366;
}
